const storageKey = "linkhub.language";
let language = "vi";
try {
  if (localStorage.getItem(storageKey) === "en") language = "en";
} catch {
  /* Storage is optional. */
}
export const locale = () => (language === "en" ? "en-US" : "vi-VN");
export function t(value) {
  const source = String(value ?? "");
  const text = source.trim().replace(/\s+/g, " ");
  return language === "en" && translations[text]
    ? source.replace(
        /^(\s*)[\s\S]*?(\s*)$/,
        (_, before, after) => before + translations[text] + after,
      )
    : source;
}
const bindings = new Map();
export function bindText(element, value) {
  const source = String(value);
  element.textContent = t(source);
  if (translations[source.trim().replace(/\s+/g, " ")])
    bindings.set(element, { element, source, last: element.textContent });
  else bindings.delete(element);
}
function render() {
  document.documentElement.lang = language;
  for (const [key, binding] of bindings) {
    if (!binding.element.isConnected) {
      bindings.delete(key);
      continue;
    }
    const current = binding.attribute
      ? binding.element.getAttribute(binding.attribute)
      : binding.element.textContent;
    // Do not overwrite content subsequently supplied by the application or a user.
    if (current !== binding.last) continue;
    binding.last = t(binding.source);
    if (binding.attribute)
      binding.element.setAttribute(binding.attribute, binding.last);
    else binding.element.textContent = binding.last;
  }
  document.querySelectorAll("[data-language-select]").forEach((select) => {
    select.value = language;
  });
}
export function setLanguage(value) {
  if (value !== "vi" && value !== "en") return;
  language = value;
  try {
    localStorage.setItem(storageKey, language);
  } catch {
    /* Keep the current page choice. */
  }
  render();
  window.dispatchEvent(
    new CustomEvent("linkhub:language-change", { detail: language }),
  );
}
function init() {
  const walker = document.createTreeWalker(document.body, NodeFilter.SHOW_TEXT);
  while (walker.nextNode()) {
    const element = walker.currentNode;
    if (
      element.parentElement.closest(
        "script,style,textarea,[data-language-select]",
      )
    )
      continue;
    if (translations[element.textContent.trim().replace(/\s+/g, " ")])
      bindings.set(element, {
        element,
        source: element.textContent,
        last: element.textContent,
      });
  }
  document
    .querySelectorAll("[title],[placeholder],[aria-label],[alt]")
    .forEach((element) => {
      for (const attribute of ["title", "placeholder", "aria-label", "alt"]) {
        const source = element.getAttribute(attribute);
        if (source && translations[source.trim().replace(/\s+/g, " ")])
          bindings.set({}, { element, attribute, source, last: source });
      }
    });
  const title = document.querySelector("title");
  if (title && translations[title.textContent])
    bindings.set(title, {
      element: title,
      source: title.textContent,
      last: title.textContent,
    });
  document
    .querySelectorAll("[data-language-select]")
    .forEach((select) =>
      select.addEventListener("change", () => setLanguage(select.value)),
    );
  render();
}
// Module scripts run after parsing, before application modules populate user data.
init();
window.addEventListener("storage", (event) => {
  if (event.key === storageKey || event.key === null) {
    language = event.newValue === "en" ? "en" : "vi";
    render();
    window.dispatchEvent(
      new CustomEvent("linkhub:language-change", { detail: language }),
    );
  }
});
